function eventRow(
  id: number,
  code: string,
  name: string,
  status: string,
  sampling: string,
  product: string,
  version: string,
  trigger: string,
): EntryRow {
  return {
    id,
    status,
    pending: status !== '已发布',
    abnormal: false,
    '事件编号': code,
    '事件名称': name,
    '事件类型': '点击/表单',
    '触发条件': trigger,
    '上报参数': 'user_id, session_id, page_id',
    '采样比例': sampling,
    '所属产品': product,
    '事件版本': version,
    '事件负责人': '埋点管理员',
  }
}

